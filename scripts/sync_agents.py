"""Generate complete native agent definitions from shared Markdown/TOML sources.

Python 3.11+ standard library only. Validate every source/output path before any
write. Individual replacements are atomic; the whole batch is not a transaction.
"""

import argparse
from dataclasses import dataclass
import json
import os
from pathlib import Path
import re
import sys
import tempfile
import tomllib


SOURCE_STEMS = ("coordinator", "requirements", "implementer", "reviewer", "completion")


@dataclass(frozen=True)
class Role:
    source: str
    name: str
    description: str
    instructions: str


def load_roles(root: Path) -> list[Role]:
    source_dir = root / "agents"
    expected = {f"{stem}.md" for stem in SOURCE_STEMS}
    actual = {path.name for path in source_dir.glob("*.md")} - {"README.md"}
    if actual != expected:
        raise ValueError(
            f"source files: missing {sorted(expected - actual)}, "
            f"unexpected {sorted(actual - expected)}; no files changed"
        )
    roles = []
    names = set()
    for stem in SOURCE_STEMS:
        path = source_dir / f"{stem}.md"
        if path.resolve() != root.resolve() / "agents" / path.name:
            raise ValueError(f"source escapes repository: {path.name}")
        text = path.read_bytes().decode("utf-8").replace("\r\n", "\n")
        if not text.startswith("+++\n") or "\n+++\n" not in text[4:]:
            raise ValueError(f"{path.name}: expected +++ TOML frontmatter and full prompt")
        metadata, instructions = text[4:].split("\n+++\n", 1)
        data = tomllib.loads(metadata)
        if set(data) != {"name", "description"}:
            raise ValueError(f"{path.name}: only name and description are allowed")
        if any(not isinstance(value, str) or not value.strip() for value in data.values()):
            raise ValueError(f"{path.name}: metadata must be nonempty strings")
        name = data["name"]
        if not re.fullmatch(r"[a-z][a-z0-9_]*", name) or name != f"wled_{stem}":
            raise ValueError(f"{path.name}: invalid role identity {name!r}")
        if name in names:
            raise ValueError(f"{path.name}: duplicate role identity {name!r}")
        if not instructions.strip():
            raise ValueError(f"{path.name}: missing full prompt")
        # Reject lone surrogates and other text that cannot form UTF-8 adapters.
        (data["description"] + instructions).encode("utf-8")
        names.add(name)
        roles.append(Role(f"agents/{path.name}", name, data["description"], instructions))
    return roles


def quoted(value: str) -> str:
    """JSON double-quoted scalars are valid TOML and YAML in this subset.

    YAML treats these Unicode line separators specially when left literal, so
    escape them explicitly. Keep other Unicode (including non-BMP text) intact.
    """
    result = json.dumps(value, ensure_ascii=False)
    for char in ("\x85", "\u2028", "\u2029"):
        result = result.replace(char, f"\\u{ord(char):04x}")
    return result


def render_codex(role: Role) -> bytes:
    text = (
        f"# Generated by scripts/sync_agents.py from {role.source}; DO NOT EDIT.\n"
        f"name = {quoted(role.name)}\n"
        f"description = {quoted(role.description)}\n"
        f"developer_instructions = {quoted(role.instructions)}\n"
    )
    # Decode through the native format, independently of the source parser.
    data = tomllib.loads(text)
    if data != {
        "name": role.name,
        "description": role.description,
        "developer_instructions": role.instructions,
    }:
        raise ValueError(f"{role.source}: Codex encoding changed role content")
    return text.encode("utf-8")


def render_claude(role: Role) -> bytes:
    # Claude requires --- on the first line; comments belong inside frontmatter.
    text = (
        "---\n"
        f"# Generated by scripts/sync_agents.py from {role.source}; DO NOT EDIT.\n"
        f"name: {quoted(role.name)}\n"
        f"description: {quoted(role.description)}\n"
        "---\n"
        + role.instructions
    )
    return text.encode("utf-8")


def outputs(root: Path) -> dict[Path, bytes]:
    """Build and validate the entire batch without changing the filesystem."""
    result = {}
    for role in load_roles(root):
        for relative, content in (
            (f".codex/agents/{role.name}.toml", render_codex(role)),
            (f".claude/agents/{role.name}.md", render_claude(role)),
        ):
            path = root / relative
            if path.resolve() != root.resolve() / relative:
                raise ValueError(f"output escapes managed repository path: {relative}")
            if path.exists() and not path.is_file():
                raise ValueError(f"output is not a file: {relative}")
            for parent in path.parents:
                if parent == root:
                    break
                if parent.exists() and not parent.is_dir():
                    raise ValueError(f"output parent is not a directory: {parent}")
            result[path] = content
    return result


def sync(root: Path, *, check: bool = False) -> list[str]:
    expected = outputs(root)
    changed = []
    for path, content in expected.items():
        try:
            current = path.read_bytes()
        except FileNotFoundError:
            current = None
        if current != content:
            changed.append(path)
    if not check:
        for path in changed:
            path.parent.mkdir(parents=True, exist_ok=True)
            temporary = None
            try:
                with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as stream:
                    temporary = Path(stream.name)
                    stream.write(expected[path])
                os.replace(temporary, path)
            finally:
                if temporary is not None and temporary.exists():
                    temporary.unlink()
    return [path.relative_to(root).as_posix() for path in changed]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="report drift without writing")
    options = parser.parse_args(argv)
    root = Path(__file__).resolve().parents[1]
    try:
        changed = sync(root, check=options.check)
    except (OSError, ValueError, UnicodeError) as exc:
        print(f"Agent synchronization failed: {exc}", file=sys.stderr)
        return 1
    if changed:
        print(("Agent adapter drift: " if options.check else "Synchronized: ") + ", ".join(changed))
    else:
        print("Agent adapters are synchronized.")
    return 1 if options.check and changed else 0


if __name__ == "__main__":
    raise SystemExit(main())
